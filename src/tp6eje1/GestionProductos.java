private void armarCabecera() {
        modelo.addColumn("Nombre");
        modelo.addColumn("Categoria");
        modelo.addColumn("Precio");
        jtProductos.setModel(modelo);
    }

    private void agregarDatos(Producto producto) {
        modelo.addRow(new Object[]{producto.getNombre(), producto.getCategoria(), producto.getPrecio()});

    }

    private void cargarCategorias() {
        // Carga automática basada en los elementos del enum Categoria
        for (Categoria cat : Categoria.values()) {
            jCbCategoria.addItem(cat.name());
        }
    }

