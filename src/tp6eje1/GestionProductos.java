    private void btAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btAgregarActionPerformed
        String nombre = txNombre.getText().trim();
        String precioStr = txPrecio.getText().trim();
        String categoria = (String) jCbCategoria.getSelectedItem();
        // 2. Validar campos vacíos
        if (nombre.isEmpty() || precioStr.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Por favor, complete todos los campos.",
                    "Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        // 3. Validar que el precio sea un número válido
        try {
            double precio = Double.parseDouble(precioStr);

            if (precio < 0) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "El precio no puede ser negativo.",
                        "Error",
                        javax.swing.JOptionPane.ERROR_MESSAGE);
                return;
            }

            // 4. Crear el objeto Producto y agregarlo usando tu método
            Producto producto = new Producto(nombre, categoria, precio);
            agregarDatos(producto);

            // 5. Limpiar los campos después de agregar
            txNombre.setText("");
            txPrecio.setText("");
            jCbCategoria.setSelectedIndex(0);

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "El precio debe ser un valor numérico.",
                    "Error de formato",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btAgregarActionPerformed

